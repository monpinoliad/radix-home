//! Wi-Fi setup mode: an open `Radix-Setup` hotspot with a captive portal where you pick the
//! network the clock should join. The choice is saved to flash and the board restarts.
//!
//! Pieces: the hotspot + scanning ([`wifi_task`]), a DHCP server that hands phones an address
//! and the portal URL ([`dhcp_task`]), a DNS server that points every name at us ([`dns_task`]),
//! and the web page itself ([`http_task`]).

